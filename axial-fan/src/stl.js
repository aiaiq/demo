// STL writers + an independent watertightness check, working on manifold-3d
// meshes (positions in mm). `scale` converts units on export (0.001 → metres).

function triangles(mesh, scale, fn) {
  const { vertProperties: v, triVerts: t, numProp: n } = mesh;
  for (let i = 0; i < t.length; i += 3) {
    const a = t[i] * n, b = t[i + 1] * n, c = t[i + 2] * n;
    const ax = v[a] * scale, ay = v[a + 1] * scale, az = v[a + 2] * scale;
    const bx = v[b] * scale, by = v[b + 1] * scale, bz = v[b + 2] * scale;
    const cx = v[c] * scale, cy = v[c + 1] * scale, cz = v[c + 2] * scale;
    let nx = (by - ay) * (cz - az) - (bz - az) * (cy - ay);
    let ny = (bz - az) * (cx - ax) - (bx - ax) * (cz - az);
    let nz = (bx - ax) * (cy - ay) - (by - ay) * (cx - ax);
    const len = Math.hypot(nx, ny, nz) || 1;
    fn(nx / len, ny / len, nz / len, ax, ay, az, bx, by, bz, cx, cy, cz);
  }
}

export function toBinarySTL(mesh, { scale = 1, name = 'solid' } = {}) {
  const count = mesh.triVerts.length / 3;
  const buf = new ArrayBuffer(84 + 50 * count);
  const view = new DataView(buf);
  const header = `${name} | binary STL | generated by axial-fan`.slice(0, 80);
  for (let i = 0; i < header.length; i++) view.setUint8(i, header.charCodeAt(i));
  view.setUint32(80, count, true);
  let o = 84;
  triangles(mesh, scale, (...f) => {
    for (const x of f) { view.setFloat32(o, x, true); o += 4; }
    o += 2; // attribute byte count
  });
  return new Uint8Array(buf);
}

// Several named solids in one ASCII file (one `solid <name>` block each).
export function toAsciiSTL(named, { scale = 1 } = {}) {
  const out = [];
  const f = (x) => x.toExponential(7);
  for (const [name, mesh] of named) {
    out.push(`solid ${name}`);
    triangles(mesh, scale, (nx, ny, nz, ...p) => {
      out.push(` facet normal ${f(nx)} ${f(ny)} ${f(nz)}`, '  outer loop');
      for (let i = 0; i < 9; i += 3) out.push(`   vertex ${f(p[i])} ${f(p[i + 1])} ${f(p[i + 2])}`);
      out.push('  endloop', ' endfacet');
    });
    out.push(`endsolid ${name}`);
  }
  return out.join('\n') + '\n';
}

// Every directed edge must appear exactly once and its reverse exactly once
// (closed + consistently oriented), with no zero-area triangles.
export function checkMesh(mesh) {
  const { vertProperties: v, triVerts: t, numProp: n } = mesh;
  const edges = new Map();
  let degenerate = 0;
  let minArea = Infinity;
  const nv = v.length / n;
  for (let i = 0; i < t.length; i += 3) {
    const ids = [t[i], t[i + 1], t[i + 2]];
    for (let e = 0; e < 3; e++) {
      const key = ids[e] * nv + ids[(e + 1) % 3];
      edges.set(key, (edges.get(key) || 0) + 1);
    }
    const [a, b, c] = ids.map((x) => x * n);
    const ux = v[b] - v[a], uy = v[b + 1] - v[a + 1], uz = v[b + 2] - v[a + 2];
    const wx = v[c] - v[a], wy = v[c + 1] - v[a + 1], wz = v[c + 2] - v[a + 2];
    const area = 0.5 * Math.hypot(uy * wz - uz * wy, uz * wx - ux * wz, ux * wy - uy * wx);
    minArea = Math.min(minArea, area);
    if (area < 1e-9) degenerate++;
  }
  let openEdges = 0;
  let duplicated = 0;
  for (const [key, count] of edges) {
    if (count > 1) duplicated++;
    const a = Math.floor(key / nv), b = key % nv;
    if (!edges.has(b * nv + a)) openEdges++;
  }
  return {
    triangles: t.length / 3,
    openEdges,
    nonManifoldEdges: duplicated,
    degenerateTriangles: degenerate,
    minTriangleArea: minArea,
    watertight: openEdges === 0 && duplicated === 0 && degenerate === 0,
  };
}

// Re-read a binary STL and weld vertices by exact float32 position — the way
// a mesher sees the file — so checkMesh() can verify the written bytes.
export function parseBinarySTL(bytes) {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const count = view.getUint32(80, true);
  const index = new Map();
  const pos = [];
  const tris = new Uint32Array(count * 3);
  for (let t = 0; t < count; t++) {
    for (let c = 0; c < 3; c++) {
      const o = 84 + t * 50 + 12 + c * 12;
      const xyz = [view.getFloat32(o, true), view.getFloat32(o + 4, true), view.getFloat32(o + 8, true)];
      const key = xyz.join(',');
      let id = index.get(key);
      if (id === undefined) { id = pos.length / 3; index.set(key, id); pos.push(...xyz); }
      tris[t * 3 + c] = id;
    }
  }
  return { numProp: 3, vertProperties: new Float32Array(pos), triVerts: tris };
}

// Read an ASCII STL into its `solid` blocks, welding vertices by their exact
// text, so each block can be checked as the closed body SimScale will see.
export function parseAsciiSTL(text) {
  const blocks = [];
  let cur = null;
  for (const line of text.split('\n')) {
    const s = line.trim();
    if (s.startsWith('solid ')) cur = { name: s.slice(6), index: new Map(), pos: [], tris: [] };
    else if (s.startsWith('vertex ') && cur) {
      let id = cur.index.get(s);
      if (id === undefined) {
        id = cur.pos.length / 3;
        cur.index.set(s, id);
        cur.pos.push(...s.split(/\s+/).slice(1).map(Number));
      }
      cur.tris.push(id);
    } else if (s.startsWith('endsolid') && cur) {
      blocks.push([cur.name, { numProp: 3, vertProperties: new Float32Array(cur.pos), triVerts: new Uint32Array(cur.tris) }]);
      cur = null;
    }
  }
  return blocks;
}
